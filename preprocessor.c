#include<stdio.h>
#define height 100
#define number 3.14
#define letter 'A'
#define letter_sequence "Hello, World!"
#define special_char '?'

int main() {
    printf("Height: %d\n", height);
    printf("Number: %.2f\n", number);
    printf("Letter: %c\n", letter);
    printf("Letter Sequence: %s\n", letter_sequence);
    printf("Special Character: %c\n", special_char);
    
    return 0;
}